#Requires -Version 5.1
<#
  Shared node-gyp environment contract for Windows qualification scripts.
  Uses process environment variables only (npm 10+ rejects legacy npm config python/msvs_version).

  Ensure-WindowsNativeBuildPrereqs.ps1 writes node-gyp.env.ps1 under EvidenceRoot.
  Callers dot-source that file (or Import-WindowsNodeGypEnv) before npm ci / node-gyp rebuild
  in the SAME process — child powershell.exe runs do not inherit these values automatically.
#>
Set-StrictMode -Version Latest

function Get-WindowsNodeGypEnvPath {
  param([Parameter(Mandatory)][string]$EvidenceRoot)
  return (Join-Path $EvidenceRoot 'node-gyp.env.ps1')
}

function Set-WindowsNodeGypProcessEnv {
  param(
    [Parameter(Mandatory)][string]$PythonExe,
    [string]$MsvsVersion = '2022'
  )
  if (-not (Test-Path -LiteralPath $PythonExe)) {
    throw "Python executable not found: $PythonExe"
  }
  $env:PYTHON = $PythonExe
  $env:npm_config_python = $PythonExe
  $env:GYP_MSVS_VERSION = $MsvsVersion
  $env:npm_config_msvs_version = $MsvsVersion
}

function Write-WindowsNodeGypEnvFile {
  param(
    [Parameter(Mandatory)][string]$EvidenceRoot,
    [Parameter(Mandatory)][string]$PythonExe,
    [string]$MsvsVersion = '2022'
  )
  New-Item -ItemType Directory -Force -Path $EvidenceRoot | Out-Null
  $path = Get-WindowsNodeGypEnvPath -EvidenceRoot $EvidenceRoot
  $escaped = $PythonExe.Replace("'", "''")
  @(
    "# Generated by Ensure-WindowsNativeBuildPrereqs.ps1 — dot-source before npm ci in this process.",
    "`$env:PYTHON = '$escaped'",
    "`$env:npm_config_python = '$escaped'",
    "`$env:GYP_MSVS_VERSION = '$MsvsVersion'",
    "`$env:npm_config_msvs_version = '$MsvsVersion'"
  ) | Set-Content -Path $path -Encoding UTF8
  return $path
}

function Import-WindowsNodeGypEnv {
  param([Parameter(Mandatory)][string]$EvidenceRoot)
  $path = Get-WindowsNodeGypEnvPath -EvidenceRoot $EvidenceRoot
  if (-not (Test-Path -LiteralPath $path)) {
    throw "Missing node-gyp env file (run Ensure-WindowsNativeBuildPrereqs first): $path"
  }
  . $path
}
