# Initialize pinned Windows depot_tools Python/CIPD metadata without updating Git.
# This gate runs before the expensive Chromium dependency sync.
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string] $DepotTools,
    [Parameter(Mandatory)]
    [ValidatePattern('^[a-f0-9]{40}$')]
    [string] $ExpectedCommit,
    [switch] $VerifyOnly
)
$ErrorActionPreference = 'Stop'
if ([Environment]::OSVersion.Platform -ne 'Win32NT') {
    throw 'Windows depot_tools readiness requires a native Windows shell.'
}
$DepotTools = (Resolve-Path -LiteralPath $DepotTools).ProviderPath
$git = (Get-Command git.exe -CommandType Application | Select-Object -First 1).Source
function Assert-Pin {
    $head = (& $git -C $DepotTools rev-parse HEAD)
    if ($LASTEXITCODE -ne 0 -or $head.Trim() -cne $ExpectedCommit) {
        throw "depot_tools revision changed: expected $ExpectedCommit; got $head."
    }
    $dirty = @(& $git -C $DepotTools status --porcelain --untracked-files=no)
    if ($LASTEXITCODE -ne 0 -or $dirty.Count) {
        throw "depot_tools tracked files changed during bootstrap: $($dirty -join '; ')."
    }
    Write-Output "PASS pinned depot_tools revision $ExpectedCommit (tracked tree clean)."
}
function Invoke-Checked {
    param([string] $File, [string[]] $Arguments)
    & $File @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "depot_tools readiness: $File exited with code $LASTEXITCODE."
    }
}
Assert-Pin
$originalPath = $env:Path
$originalUpdate = $env:DEPOT_TOOLS_UPDATE
$originalToolchain = $env:DEPOT_TOOLS_WIN_TOOLCHAIN
try {
    # Keep the version pinned even if a wrapper tries to run an update.
    $env:Path = "$DepotTools;$originalPath"
    $env:DEPOT_TOOLS_UPDATE = '0'
    $env:DEPOT_TOOLS_WIN_TOOLCHAIN = '0'
    $winTools = Join-Path $DepotTools 'bootstrap/win_tools.bat'
    $cipdSetup = Join-Path $DepotTools 'cipd_bin_setup.bat'
    foreach ($name in @('gclient.bat', 'gn.bat', 'autoninja.bat',
                        'bootstrap/bootstrap.py', 'bootstrap/manifest.txt',
                        'bootstrap/win_tools.bat', 'cipd_bin_setup.bat',
                        'gn.py', 'autoninja.py')) {
        if (!(Test-Path -LiteralPath (Join-Path $DepotTools $name) -PathType Leaf)) {
            throw "Pinned depot_tools checkout is missing required source file: $name."
        }
    }
    $metadata = Join-Path $DepotTools 'python3_bin_reldir.txt'
    if (!$VerifyOnly) {
        # Chromium's documented Windows bootstrap installs the manifest-pinned
        # CPython via CIPD and generates python3_bin_reldir.txt. Calling
        # update_depot_tools.bat would also fetch/checkout origin/main: do NOT.
        Write-Output 'BEGIN pinned Windows depot_tools bootstrap/win_tools.bat (no Git update).'
        Invoke-Checked $winTools @()
        Write-Output 'PASS Windows Python bootstrap script.'
        Write-Output 'BEGIN depot_tools CIPD tool bootstrap (no Git update).'
        Invoke-Checked $cipdSetup @()
        Write-Output 'PASS depot_tools CIPD bootstrap.'
    }
    Assert-Pin
    if (!(Test-Path -LiteralPath $metadata -PathType Leaf)) {
        throw 'Python bootstrap incomplete: python3_bin_reldir.txt is absent. The supported bootstrap/win_tools.bat must succeed before Chromium sync.'
    }
    $relative = (Get-Content -LiteralPath $metadata -Raw).Trim()
    if (!$relative -or [IO.Path]::IsPathRooted($relative)) {
        throw "Invalid generated depot_tools Python location metadata: '$relative'."
    }
    $pythonDir = [IO.Path]::GetFullPath((Join-Path $DepotTools $relative))
    $root = $DepotTools.TrimEnd('\') + '\'
    if (!$pythonDir.StartsWith($root, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Generated depot_tools Python location escapes its checkout: $relative."
    }
    $pythonExe = Join-Path $pythonDir 'python3.exe'
    if (!(Test-Path -LiteralPath $pythonExe -PathType Leaf)) {
        throw "Generated depot_tools Python metadata points to a missing interpreter: $pythonExe."
    }
    Write-Output "PASS generated Python metadata: $relative and installed Python executable."
    Invoke-Checked $pythonExe @('-c', 'import sys; print("PASS depot_tools bundled CPython " + sys.version.split()[0])')
    $launchers = @(
        (Join-Path $DepotTools 'python-bin/python3.bat'),
        (Join-Path $DepotTools 'python3.bat')
    )
    $pythonLauncher = @($launchers | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf } | Select-Object -First 1)
    if (!$pythonLauncher.Count) {
        throw 'No Python 3 Windows batch launcher was generated by depot_tools bootstrap.'
    }
    Invoke-Checked $pythonLauncher[0] @('-c', 'import sys; print("PASS depot_tools Python batch launcher " + sys.version.split()[0])')
    # Static readiness test before Chromium checkout: GN's actual executable is
    # provided by Chromium's DEPS, so a real gn --version must wait for sync.
    Invoke-Checked $pythonExe @(
        '-c',
        'import ast,pathlib,sys; root=pathlib.Path(sys.argv[1]); [ast.parse((root/n).read_text(encoding="utf-8"),filename=n) for n in ("gn.py","autoninja.py","gclient.py")]; print("PASS GN, autoninja and gclient Python entrypoints parse")',
        $DepotTools
    )
    $cmd = (Get-Command cmd.exe -CommandType Application | Select-Object -First 1).Source
    if (!$cmd) { throw 'cmd.exe is unavailable for Windows GN and Ninja wrappers.' }
    foreach ($launcher in @('gn.bat', 'autoninja.bat', 'gclient.bat')) {
        Write-Output "PASS Windows launcher exists for cmd.exe: $launcher"
    }
    Write-Output "PATH first entry: $(($env:Path -split ';')[0])"
    Write-Output "DEPOT_TOOLS_UPDATE=$env:DEPOT_TOOLS_UPDATE; DEPOT_TOOLS_WIN_TOOLCHAIN=$env:DEPOT_TOOLS_WIN_TOOLCHAIN."
    Write-Output 'PASS depot_tools Python bootstrap readiness before Chromium synchronization.'
    Assert-Pin
} finally {
    $env:Path = $originalPath
    $env:DEPOT_TOOLS_UPDATE = $originalUpdate
    $env:DEPOT_TOOLS_WIN_TOOLCHAIN = $originalToolchain
}
